export function calculateFeedbackMetrics(feedbacks: FarmerRecommendationFeedback[]) {
  if (!feedbacks || feedbacks.length === 0) {
    return {
      totalLogged: 0,
      adherenceRatePercent: 0,
      avgSatisfaction: 0,
      avgRealizedVariancePerQtl: 0,
      totalNetValueRealized: 0,
      topReportedIssues: [],
    };
  }

  const totalLogged = feedbacks.length;
  const followedCount = feedbacks.filter(f => f.followedRecommendation === 'yes' || f.followedRecommendation === 'partially').length;
  const adherenceRatePercent = Math.round((followedCount / totalLogged) * 100);

  const avgSatisfaction = +(feedbacks.reduce((acc, f) => acc + f.satisfactionRating, 0) / totalLogged).toFixed(1);
  const avgRealizedVariancePerQtl = Math.round(feedbacks.reduce((acc, f) => acc + f.realizedVariancePerQtl, 0) / totalLogged);
  const totalNetValueRealized = feedbacks.reduce((acc, f) => acc + f.actualNetRealized, 0);

  // Issue frequency aggregation
  const issueCounts: Record<string, number> = {};
  feedbacks.forEach(f => {
    f.issuesEncountered.forEach(issue => {
      if (issue !== 'None - Smooth transaction') {
        issueCounts[issue] = (issueCounts[issue] || 0) + 1;
      }
    });
  });

  const topReportedIssues = Object.entries(issueCounts)
    .map(([issue, count]) => ({ issue, count }))
    .sort((a, b) => b.count - a.count);

  return {
    totalLogged,
    adherenceRatePercent,
    avgSatisfaction,
    avgRealizedVariancePerQtl,
    totalNetValueRealized,
    topReportedIssues,
  };
}
